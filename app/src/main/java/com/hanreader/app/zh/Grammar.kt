package com.hanreader.app.zh

/**
 * A grammar construction: its marker words in order (虽然 … 但是), what it means, and an example.
 * [parts]: each part is a set of alternative tokens; part k+1 follows part k within [maxGap] tokens.
 * [check]: an extra condition on the sentence's tokens and the matched positions.
 */
class GrammarPoint(
    val title: String,
    val explanation: String,
    val example: String,
    val exampleRu: String,
    internal val parts: List<Set<String>>,
    internal val maxGap: Int = 12,
    internal val check: (List<String>, IntArray) -> Boolean = { _, _ -> true },
    /** Dictionary words that are the whole construction in one token (从早到晚, 对我来说). */
    internal val whole: Set<String> = emptySet()
)

/** A construction found in a sentence; [positions] are the indices of its marker tokens. */
class GrammarMatch(val point: GrammarPoint, val positions: IntArray)

/**
 * Common grammar constructions found by their marker words in a segmented sentence. Offline and
 * rule-based: a marker must be its own token (虽然, 把), later markers follow within a few tokens.
 * Explanations and examples are written for HanReader.
 */
object Grammar {
    /** Constructions with marker token [i] among the tokens [tokens] of one sentence. */
    fun at(tokens: List<String>, i: Int): List<GrammarMatch> = find(tokens).filter { m -> i in m.positions }

    /** Every construction in the tokens of one sentence, at most one match per construction and start. */
    fun find(tokens: List<String>): List<GrammarMatch> {
        val out = ArrayList<GrammarMatch>()
        for (p in POINTS) {
            val one = tokens.indexOfFirst { it in p.whole }
            if (one >= 0) { out += GrammarMatch(p, intArrayOf(one)); continue }
            for (start in tokens.indices) {
                if (tokens[start] !in p.parts[0]) continue
                val pos = IntArray(p.parts.size)
                pos[0] = start
                var ok = true
                for (k in 1 until p.parts.size) {
                    val from = pos[k - 1] + 1
                    val to = minOf(tokens.lastIndex, pos[k - 1] + 1 + p.maxGap)
                    val j = (from..to).firstOrNull { tokens[it] in p.parts[k] }
                    if (j == null) { ok = false; break }
                    pos[k] = j
                }
                if (ok && p.check(tokens, pos)) { out += GrammarMatch(p, pos); break }
            }
        }
        return out
    }

